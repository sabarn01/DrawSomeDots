// Playwright-driven calibration. Spawns Vite dev, opens the calibrate.html
// fixture in headless chromium, runs the REAL drawDigit against every
// (font × digit × size) combination, and writes the results as a
// checked-in TypeScript module the app can import at startup.
//
// Run with:  npm run calibrate
//
// Output:  web/src/renderer/calibrationData.ts

import { spawn } from "node:child_process";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { chromium } from "playwright";

const __dirname = dirname(fileURLToPath(import.meta.url));
const webRoot = resolve(__dirname, "..");
const outFile = resolve(webRoot, "src/renderer/calibrationData.ts");

const FONTS = [
  "Comic Sans MS",
  "Arial",
  "Georgia",
  "Courier New",
  "Impact",
  "Verdana",
];

// Sample sizes span the practical runtime range. The aggregation biases
// toward the largest sizes because runtime letter sizes for realistic N
// (10k–1M+) land in the several-hundred-px range.
const SIZES = [200, 320, 460, 620, 780];

async function waitForServer(url, timeoutMs = 30_000) {
  const start = Date.now();
  while (Date.now() - start < timeoutMs) {
    try {
      const res = await fetch(url);
      if (res.ok) return;
    } catch {
      // not up yet
    }
    await new Promise((r) => setTimeout(r, 250));
  }
  throw new Error(`Vite dev server did not come up at ${url}`);
}

async function main() {
  const port = 5177;
  const vite = spawn("npx", ["vite", "--port", String(port), "--strictPort"], {
    cwd: webRoot,
    stdio: ["ignore", "pipe", "pipe"],
    shell: process.platform === "win32",
  });
  vite.stdout.on("data", (d) => process.stdout.write(`[vite] ${d}`));
  vite.stderr.on("data", (d) => process.stderr.write(`[vite] ${d}`));

  try {
    await waitForServer(`http://localhost:${port}/`);

    const browser = await chromium.launch({ headless: true });
    const context = await browser.newContext({ viewport: { width: 1200, height: 800 } });
    const page = await context.newPage();
    page.on("console", (msg) => console.log(`[page] ${msg.text()}`));
    page.on("pageerror", (err) => console.error(`[pageerror] ${err.message}`));

    await page.goto(`http://localhost:${port}/calibrate.html`);
    await page.waitForFunction(() => typeof window.__runCalibration === "function", { timeout: 15_000 });

    console.log(`Running calibration for ${FONTS.length} fonts × ${SIZES.length} sizes × 10 digits ...`);
    const t0 = Date.now();
    const results = await page.evaluate(
      async ({ fonts, sizes }) => await window.__runCalibration(fonts, sizes),
      { fonts: FONTS, sizes: SIZES },
    );
    console.log(`Calibration done in ${Math.round((Date.now() - t0) / 1000)}s`);

    await browser.close();

    await writeCalibrationFile(results);
    console.log(`Wrote ${outFile}`);
  } finally {
    vite.kill();
  }
}

async function writeCalibrationFile(results) {
  const entries = results.map((r) => {
    const dpp = new Array(10).fill(0);
    const perSize = new Array(10).fill(null).map(() => []);
    let weightSum = 0;
    for (let i = 0; i < r.perDigit[0].perSize.length; i++) weightSum += i + 1;
    for (const pd of r.perDigit) {
      let acc = 0;
      for (let i = 0; i < pd.perSize.length; i++) {
        const s = pd.perSize[i];
        acc += s.dotsPerPixel * (i + 1);
        perSize[pd.digit].push({ size: s.size, letterWidth: s.letterWidth, placed: s.placed, dotsPerPixel: s.dotsPerPixel });
      }
      dpp[pd.digit] = acc / weightSum;
    }
    return { font: r.font, dotsPerPixel: dpp, perSize };
  });

  const header = `// AUTO-GENERATED by scripts/run-calibrate.mjs — do not edit by hand.
// Run \`npm run calibrate\` to regenerate. Measured against the real
// drawDigit algorithm via Playwright + headless Chromium.
//
// Sample sizes used: ${JSON.stringify(results[0]?.perDigit[0]?.perSize.map((s) => s.size) ?? [])}
// Generated: ${new Date().toISOString()}

export interface BakedCalibration {
  font: string;
  /** dotsPerPixel[d] aggregated across sample sizes, biased toward large sizes. */
  dotsPerPixel: number[];
  /** perSize[d] = raw per-size measurements for digit d, ordered small \u2192 large. */
  perSize: { size: number; letterWidth: number; placed: number; dotsPerPixel: number }[][];
}

export const BAKED_CALIBRATIONS: BakedCalibration[] = ${JSON.stringify(entries, null, 2)};

/** Case-insensitive lookup. Returns null when no baked data exists for the font. */
export function findBakedCalibration(fontFamily: string): BakedCalibration | null {
  const key = fontFamily.toLowerCase();
  for (const c of BAKED_CALIBRATIONS) {
    if (c.font.toLowerCase() === key) return c;
  }
  return null;
}
`;
  await writeFile(outFile, header, "utf8");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
